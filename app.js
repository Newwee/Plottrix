// =========================================================================
// 13. ENHANCED GEMINI API CALL WITH SMART ROUTING & CONTEXT CACHING FALLBACK
// =========================================================================
async function callGeminiStructured(systemInstruction, userPrompt, responseSchema, taskType = "core") {
  const key = getActiveApiKey();
  const compiledSkills = compileActiveSkillsPrompt();
  const fullSystemInstruction = systemInstruction + compiledSkills;

  const payload = {
    contents: [{ parts: [{ text: userPrompt }] }],
    systemInstruction: { parts: [{ text: fullSystemInstruction }] },
    generationConfig: {
      responseMimeType: "application/json",
      responseSchema: responseSchema
    }
  };

  const isHttp = window.location.protocol.startsWith("http");
  const primaryModel = MODEL_ROUTING[taskType] || MODEL_ROUTING.core;
  const modelsToTry = [primaryModel, MODEL_ROUTING.core, MODEL_ROUTING.fallback];
  const uniqueModels = [...new Set(modelsToTry)];

  for (const model of uniqueModels) {
    const delays = [1000, 2000, 4000];
    for (let attempt = 0; attempt <= delays.length; attempt++) {
      try {
        let result = null;
        if (isHttp) {
          try {
            const response = await fetch("/api/gemini", {
              method: "POST",
              headers: {
                "Content-Type": "application/json",
                "X-Client-Plan": appState.plan
              },
              body: JSON.stringify({
                payload,
                model,
                taskType,
                plan: appState.plan,
                apiKey: key,
                useCaching: (appState.plan !== "Free Plan")
              })
            });

            if (response.ok) {
              result = await response.json();
            } else if (response.status === 429) {
              const errData = await response.json().catch(() => ({}));
              throw new Error(errData?.error?.message || "ติด Cooldown กรุณารอสักครู่");
            } else if (response.status === 503 || response.status === 404) {
              throw new Error(`Model ${model} returned status ${response.status}`);
            } else {
              const errData = await response.json().catch(() => ({}));
              throw new Error(errData?.error?.message || `HTTP ${response.status}`);
            }
          } catch (srvErr) {
            if (srvErr.message && srvErr.message.includes("Cooldown")) {
              throw srvErr;
            }
            // Direct client fallback
            const directUrl = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${key}`;
            const directResp = await fetch(directUrl, {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify(payload)
            });
            if (!directResp.ok) {
              const errData = await directResp.json().catch(() => ({}));
              throw new Error(errData?.error?.message || `HTTP ${directResp.status}`);
            }
            result = await directResp.json();
          }
        } else {
          // Direct client call
          const directUrl = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${key}`;
          const directResp = await fetch(directUrl, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(payload)
          });
          if (!directResp.ok) {
            const errData = await directResp.json().catch(() => ({}));
            throw new Error(errData?.error?.message || `HTTP ${directResp.status}`);
          }
          result = await directResp.json();
        }

        const jsonText = result?.candidates?.[0]?.content?.parts?.[0]?.text;
        if (!jsonText) throw new Error("Empty response from Gemini");
        return JSON.parse(jsonText);

      } catch (err) {
        console.warn(`Attempt ${attempt + 1} with ${model} failed:`, err);
        if (err.message && err.message.includes("Cooldown")) throw err;
        if (err.message && (err.message.includes("503") || err.message.includes("high demand") || err.message.includes("404"))) {
          break; // Switch to fallback model
        }
        if (attempt === delays.length) {
          if (model === uniqueModels[uniqueModels.length - 1]) throw err;
        } else {
          await new Promise(r => setTimeout(r, delays[attempt]));
        }
      }
    }
  }
  throw new Error("Unable to obtain response from Gemini API");
}

