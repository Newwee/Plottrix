function createVersionSnapshot(note = "บันทึกอัตโนมัติ") {
  const ch = getActiveChapter();
  const fullText = (ch.pages || []).join("\n\n");
  if (!fullText.trim()) return;

  if (!appState.versionHistory) appState.versionHistory = [];
  const snapshot = {
    id: "v-" + Date.now(),
    timestamp: new Date().toLocaleString("th-TH"),
    chapterId: ch.id,
    chapterTitle: `ตอนที่ ${ch.number} ${ch.title || ''}`,
    wordCount: fullText.trim().split(/\s+/).length,
    charCount: fullText.length,
    note: note,
    content: fullText
  };

  appState.versionHistory.unshift(snapshot);
  if (appState.versionHistory.length > 50) {
    appState.versionHistory = appState.versionHistory.slice(0, 50);
  }
  saveAppState();
}

function restoreVersionSnapshot(id) {
  const snapshot = (appState.versionHistory || []).find(v => v.id === id);
  if (!snapshot) return;

  if (confirm(`คุณต้องการย้อนคืนเนื้อหากลับไปที่เวอร์ชัน "${snapshot.timestamp}" ใช่หรือไม่?`)) {
    createVersionSnapshot("สำรองก่อนย้อนคืนเวอร์ชัน");
    const ch = getActiveChapter();
    ch.pages = [snapshot.content];
    appState.activePageIdx = 0;
    const editor = document.getElementById("novel-editor");
    if (editor) editor.value = snapshot.content;
    updateWordAndCharStats();
    closeHistoryModal();
    saveAppState();
    showToast(`ย้อนคืนเนื้อหากลับไปที่เวอร์ชัน ${snapshot.timestamp} สำเร็จ`, "emerald");
  }
}

