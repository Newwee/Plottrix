// 4. TECHNICAL CONDITION 1: DYNAMIC VOCABULARY INJECTION
// (ส่งเฉพาะหมวดพื้นฐาน + หมวดที่ตรงกับแนวเรื่อง ห้ามส่งทั้ง 20 หมวดเพื่อประหยัด Token)
